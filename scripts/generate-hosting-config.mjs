import assert from 'node:assert/strict';
import { readFile, writeFile, access } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { securityHeaders, privateFilePattern, blockedPublicPath } from './security-policy.mjs';
import { inspectPublicBuild } from './public-build.mjs';

// Run after prerender.mjs so Apache uses the exact origin and routes in this build.
// This writes the build directory only; it never connects to a live web server.
const root = fileURLToPath(new URL('../', import.meta.url));
const dist = path.join(root, 'dist');
const manifest = JSON.parse(await readFile(path.join(dist, 'seo-manifest.json'), 'utf8'));
const hosting = JSON.parse(await readFile(path.join(root, 'vercel.json'), 'utf8'));
const origin = new URL(manifest.siteOrigin);
assert.deepEqual(Object.fromEntries(hosting.headers.find(rule => rule.source === '/(.*)')?.headers.map(({ key, value }) => [key, value]) || []),
  { ...securityHeaders, 'Cache-Control': 'public, max-age=0, must-revalidate' }, 'Vercel security/cache headers differ from the shared production policy.');

await inspectPublicBuild(dist, { check: process.argv.includes('--check') });
assert(origin.protocol === 'https:' && origin.origin === manifest.siteOrigin && !origin.username && !origin.password,
  'The SEO manifest must specify one HTTPS origin without credentials, path, query or fragment.');
assert(/^[a-z0-9.-]+(?::[0-9]+)?$/i.test(origin.host), 'Unsupported canonical hostname.');
assert(hosting.cleanUrls === true && hosting.trailingSlash === false && !hosting.rewrites?.length,
  'Apache generation requires clean static URLs and no Vercel rewrite fallback.');

const regexEscape = value => value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const validRoute = route => route === '/' || /^\/(?:[A-Za-z0-9_-]+\/)*[A-Za-z0-9_-]+$/.test(route);
const routes = manifest.pages.map(page => page.path);
assert(routes.includes('/') && new Set(routes).size === routes.length && routes.every(validRoute), 'Invalid or duplicate rendered routes.');
assert(!routes.includes('/404'), 'The error page must not be an indexable manifest route.');
for (const route of [...routes, '/404']) {
  await access(path.join(dist, route === '/' ? 'index.html' : `${route.slice(1)}.html`));
}
const notFound = await readFile(path.join(dist, '404.html'), 'utf8');
assert(/name="robots"[^>]*content="noindex, follow"/.test(notFound), '404.html must contain its noindex metadata.');
assert(!notFound.includes('rel="canonical"'), 'The error page must not canonicalize to an indexable page.');

const migrations = hosting.redirects.filter(rule => !rule.has);
assert(migrations.length && migrations.every(rule => validRoute(rule.source) && rule.source !== '/' && routes.includes(rule.destination)
  && rule.source !== rule.destination && rule.permanent === true), 'Unsupported or invalid migration redirect.');
assert(new Set(migrations.map(rule => rule.source)).size === migrations.length, 'Duplicate migration source.');
assert(migrations.every(rule => !routes.includes(rule.source)), 'A migration source must not shadow a rendered route.');
assert(hosting.redirects.filter(rule => rule.has).every(rule => rule.source === '/:path*'
  && rule.has.length === 1 && rule.has[0].type === 'host' && rule.permanent === true),
  'Unexpected conditional redirects: update the Apache generator before deployment.');

const canonicalOrigin = origin.origin;
const lines = [
  '# Generated by scripts/generate-hosting-config.mjs; do not edit build output.',
  `# Canonical origin: ${canonicalOrigin}`,
  '# Apache 2.4+, at the domain document root. See docs/SEO-APACHE-DEPLOYMENT.md.',
  '# Behind a trusted TLS terminator, the provider MUST set ORBIT_TRUSTED_HTTPS=1',
  '# for verified HTTPS requests before enabling this file. Client headers are not trusted.',
  'Options -Indexes -MultiViews',
  'DirectoryIndex index.html',
  'ErrorDocument 404 /404.html',
  'ErrorDocument 403 default',
  '',
  'RewriteEngine On',
  '',
  '# Deny private/source files and legacy server executables, including PATH_INFO.',
  '# This must precede redirects and the existing-file bypass.',
  `RewriteRule "${privateFilePattern.source}" - [F,L,NC]`,
  '',
  '# Allow only the internal 404 error document through with its original status.',
  'RewriteCond %{ENV:REDIRECT_STATUS} =404',
  'RewriteRule ^404\\.html$ - [END]',
  '',
  '# Legacy redirects point directly to the canonical replacement and retain queries.',
  ...migrations.map(rule => `RewriteRule ^${regexEscape(rule.source.slice(1))}/*$ ${canonicalOrigin}${rule.destination} [R=308,L]`),
  '',
  '# THE_REQUEST distinguishes an explicit HTML request from an internal clean-URL rewrite.',
  'RewriteCond %{THE_REQUEST} "\\s/+index\\.html[?\\s]"',
  `RewriteRule ^index\\.html$ ${canonicalOrigin}/ [R=308,L]`,
];

for (const route of [...routes.filter(route => route !== '/'), '/404']) {
  const pattern = regexEscape(route.slice(1));
  lines.push(
    `RewriteCond %{THE_REQUEST} "\\s/+${pattern}\\.html[?\\s]"`,
    `RewriteRule ^${pattern}\\.html$ ${canonicalOrigin}${route} [R=308,L]`,
    `RewriteRule ^${pattern}/+$ ${canonicalOrigin}${route} [R=308,L]`,
  );
}

lines.push(
  '',
  '# The target host is fixed, never reflected from an untrusted Host header.',
  `RewriteCond %{HTTP_HOST} !^${regexEscape(origin.host)}$ [NC]`,
  '# Keep the original encoded path, including spaces in asset filenames.',
  'RewriteCond %{THE_REQUEST} "\\s(/[^?\\s]*)(?:\\?[^\\s]*)?\\s"',
  `RewriteRule ^ ${canonicalOrigin}%1 [R=308,L,NE]`,
  '',
  '# Direct TLS or a provider-verified HTTPS marker prevents redirect loops.',
  'RewriteCond %{HTTPS} !=on',
  'RewriteCond %{ENV:ORBIT_TRUSTED_HTTPS} !=1',
  'RewriteCond %{ENV:REDIRECT_ORBIT_TRUSTED_HTTPS} !=1',
  'RewriteCond %{THE_REQUEST} "\\s(/[^?\\s]*)(?:\\?[^\\s]*)?\\s"',
  `RewriteRule ^ ${canonicalOrigin}%1 [R=308,L,NE]`,
  '',
  '# Direct requests to the error route also return 404, not a soft 404.',
  'RewriteRule ^404$ - [R=404,L]',
  '',
  '# Immutable caching applies to existing Vite assets only, never to a missing asset.',
  'RewriteCond %{REQUEST_FILENAME} -f',
  'RewriteRule ^assets/ - [E=ORBIT_IMMUTABLE_ASSET:1]',
  '',
  '# Preserve existing files (verification proofs, images, robots, sitemap and assets).',
  'RewriteCond %{REQUEST_FILENAME} -f',
  'RewriteRule ^ - [END]',
  '',
  '# Explicit routes are required: /products and /solutions also have real subdirectories.',
  'RewriteRule ^$ index.html [END]',
  ...routes.filter(route => route !== '/').map(route => `RewriteRule ^${regexEscape(route.slice(1))}$ ${route.slice(1)}.html [END]`),
  '',
  '# Unknown routes use the custom error document and keep an actual 404 status.',
  '# There is deliberately no index.html/SPA catch-all and no PHP/CMS fallback.',
  'RewriteRule ^ - [R=404,L]',
  '',
  '# Same public security headers as vercel.json.',
  ...Object.entries(securityHeaders).map(([key, value]) => `Header always set ${key} "${value}"`),
  ...(manifest.indexable === false ? ['Header always set X-Robots-Tag "noindex, follow"'] : []),
  'Header set Cache-Control "public, max-age=31536000, immutable" env=ORBIT_IMMUTABLE_ASSET',
  '<FilesMatch "^(?!404\\.html$).*\\.html$">',
  '  Header set Cache-Control "public, max-age=0, must-revalidate"',
  '</FilesMatch>',
  '<Files "404.html">',
  '  Header always set X-Robots-Tag "noindex, follow"',
  '  Header always set Cache-Control "no-store"',
  '</Files>',
  '',
  '# Explicit content types avoid strict MIME failures on older shared hosting.',
  'AddType text/html .html',
  'AddType text/javascript .js .mjs',
  'AddType text/css .css',
  'AddType application/json .json',
  'AddType application/xml .xml',
  'AddType text/plain .txt',
  'AddType image/svg+xml .svg',
  'AddType image/webp .webp',
  'AddType image/avif .avif',
  'AddType image/png .png',
  'AddType image/jpeg .jpg .jpeg',
  'AddType application/pdf .pdf',
  'AddType video/mp4 .mp4',
  'AddCharset UTF-8 .html .js .mjs .css .json .xml .txt',
  '',
);
const configuration = lines.join('\n');
const destination = path.join(dist, '.htaccess');
if (process.argv.includes('--check')) {
  assert.equal(await readFile(destination, 'utf8'), configuration, 'dist/.htaccess is stale; regenerate it after prerendering.');
  console.log(`Apache configuration matches ${routes.length} rendered routes, ${migrations.length} migrations and ${canonicalOrigin}.`);
} else {
  await writeFile(destination, configuration);
  console.log(`Generated dist/.htaccess: ${routes.length} clean routes, ${migrations.length} permanent migrations, canonical HTTPS and real noindex 404s.`);
}
